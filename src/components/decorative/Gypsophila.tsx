import type { CSSProperties } from 'react';
import bouquet from '../../assets/decor/gypsophila-bouquet.svg';
import cornerAlt from '../../assets/decor/gypsophila-corner-alt.svg';
import corner from '../../assets/decor/gypsophila-corner.svg';
import sprig from '../../assets/decor/gypsophila-sprig.svg';
import { cx } from '../../lib/cx';

const SOURCES = { corner, cornerAlt, bouquet, sprig } as const;

/** Where each illustration's stems gather — the natural pivot for a breeze. */
const STEM_BASE: Record<keyof typeof SOURCES, string> = {
  corner: '2% 98%',
  cornerAlt: '2% 98%',
  sprig: '4% 96%',
  bouquet: '50% 74%',
};

export type GypsophilaVariant = keyof typeof SOURCES;

interface GypsophilaProps {
  variant: GypsophilaVariant;
  /** Positioning, size and rotation of the illustration. */
  className?: string;
  style?: CSSProperties;
  /** Mirror horizontally and/or vertically. */
  flip?: 'x' | 'y' | 'xy';
  /** Load immediately (above the fold). */
  eager?: boolean;
  /** Gentle breeze animation, pivoting at the stems. */
  sway?: boolean;
  /** Absolutely positioned decoration (default) or part of the layout flow. */
  inFlow?: boolean;
  /** Offsets the sway so neighbouring sprays don't move in unison. */
  swayDelay?: number;
}

const FLIP: Record<NonNullable<GypsophilaProps['flip']>, string> = {
  x: 'scale(-1, 1)',
  y: 'scale(1, -1)',
  xy: 'scale(-1, -1)',
};

/**
 * Baby's-breath illustration (original vector art generated by
 * scripts/generate-florals.mjs). Purely decorative, hidden from assistive tech.
 *
 * The outer element carries placement, rotation and mirroring; the inner image
 * sways around its own stem base, so the two never interfere.
 */
export function Gypsophila({
  variant,
  className,
  style,
  flip,
  eager = false,
  sway = false,
  inFlow = false,
  swayDelay = 0,
}: GypsophilaProps) {
  return (
    <span
      aria-hidden="true"
      className={cx('pointer-events-none block select-none', !inFlow && 'absolute', className)}
      style={flip ? { ...style, transform: `${style?.transform ?? ''} ${FLIP[flip]}`.trim() } : style}
    >
      <img
        src={SOURCES[variant]}
        alt=""
        draggable={false}
        decoding="async"
        loading={eager ? 'eager' : 'lazy'}
        className={cx('block h-auto w-full', sway && 'anim-sway')}
        style={{
          // Soft shadow that lifts the white blooms off the ivory paper.
          filter: 'drop-shadow(0 0.6px 0.8px rgb(94 75 51 / 0.34))',
          ...(sway ? ({ '--origin': STEM_BASE[variant], animationDelay: `${-swayDelay}s` } as CSSProperties) : null),
        }}
      />
    </span>
  );
}
